/** Whether a publisher has a mark, so a caller can fall back to a letter. */
export function hasPublisherLogo(publisher: string | undefined): boolean {
  return Boolean(publisher && (publisher in MONO || publisher in COLOUR));
}

export function PublisherLogo({
  publisher,
  className,
}: {
  publisher: string;
  className?: string;
}) {
  const colour = COLOUR[publisher];
  if (colour) {
    return (
      <svg viewBox={colour.viewBox} aria-hidden className={cn("size-4", className)}>
        {colour.shapes}
      </svg>
    );
  }
  const mono = MONO[publisher];
  if (!mono) return null;
  return (
    <svg viewBox="0 0 24 24" aria-hidden className={cn("size-4", className)}>
      <path fill="currentColor" d={mono} />
    </svg>
  );
}
